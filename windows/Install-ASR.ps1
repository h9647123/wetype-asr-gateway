param(
    [Parameter(Mandatory=$true)][string]$PayloadDirectory,
    [Parameter(Mandatory=$true)][string]$GatewayAddress,
    [Parameter(Mandatory=$true)][string]$KeyFile,
    [string]$InstallDirectory = 'C:\WeTypeASR'
)
$ErrorActionPreference = 'Stop'
if (!( ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator) )) { throw 'Run from an elevated PowerShell window.' }
$installer = Join-Path $PayloadDirectory 'WeTypeSetup.exe'
$archive = Join-Path $PayloadDirectory 'bridge.zip'
$sig = Get-AuthenticodeSignature $installer
if ($sig.Status -ne 'Valid' -or $sig.SignerCertificate.Subject -notmatch 'Tencent') { throw 'Expected a valid Tencent Authenticode signature.' }
$expected = '1db6c3664dde9883a1c08fe39c3834e7d44c767cc734a248865aeded6a4390f8'
if ((Get-FileHash $archive -Algorithm SHA256).Hash.ToLower() -ne $expected) { throw 'Expected upstream WeChatASRBridge v0.3.3 portable checksum.' }
$key = (Get-Content $KeyFile -Raw).Trim()
if ($key.Length -lt 24 -or $key -match '\s') { throw 'Use the strong key generated by init_config.py.' }
$address = $null
if (![Net.IPAddress]::TryParse($GatewayAddress, [ref]$address)) { throw 'GatewayAddress must be the exact gateway IP allowed through Windows Firewall.' }
if (Test-Path (Join-Path $InstallDirectory 'api-key.txt')) { throw 'Existing installation detected. Back it up and perform an explicit upgrade instead.' }
New-Item -ItemType Directory -Path $InstallDirectory -Force | Out-Null
& icacls.exe $InstallDirectory /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'Failed to protect installation directory.' }
Expand-Archive $archive -DestinationPath $InstallDirectory -Force
Copy-Item (Join-Path $PSScriptRoot 'Start-ASR.ps1') (Join-Path $InstallDirectory 'Start-ASR.ps1')
[IO.File]::WriteAllText((Join-Path $InstallDirectory 'api-key.txt'), $key, [Text.Encoding]::ASCII)
$install = Start-Process $installer -ArgumentList '/S' -PassThru -Wait
if ($install.ExitCode -notin @(0,3010)) { throw 'WeType installation failed.' }
New-NetFirewallRule -DisplayName 'WeType ASR gateway only' -Direction Inbound -Action Allow -Protocol TCP -LocalPort 8765 -RemoteAddress $GatewayAddress -Profile Any | Out-Null
$action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument ('-NoProfile -ExecutionPolicy Bypass -File "' + (Join-Path $InstallDirectory 'Start-ASR.ps1') + '"')
$trigger = New-ScheduledTaskTrigger -AtStartup
$trigger.Delay = 'PT30S'
$settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1) -ExecutionTimeLimit ([TimeSpan]::Zero) -MultipleInstances IgnoreNew
$principal = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
Register-ScheduledTask -TaskName 'WeType-ASR' -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Force | Out-Null
powercfg.exe /change standby-timeout-ac 0
powercfg.exe /change hibernate-timeout-ac 0
Start-ScheduledTask -TaskName 'WeType-ASR'
Write-Output 'ASR startup task installed. No desktop auto-login or activation configuration was added.'
